#!/usr/bin/env python3
"""Generate Custom Metadata records from knowledge/recommended-settings.json (single source of truth).
Usage: python3 scripts/build-cmdt.py   (run from the repo root; re-run after editing the pack)"""
import json, os, re, html, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'force-app/main/default/customMetadata')
pack = json.load(open(os.path.join(ROOT, 'knowledge/recommended-settings.json')))
os.makedirs(OUT, exist_ok=True)
for f in glob.glob(os.path.join(OUT, 'Codey_*.md-meta.xml')): os.remove(f)

def dev(s): return re.sub(r'[^A-Za-z0-9]+', '_', s).strip('_')[:40].rstrip('_')
def val(name, v, t='xsd:string'):
    if v is None or v == '': return f'    <values>\n        <field>{name}</field>\n        <value xsi:nil="true"/>\n    </values>'
    if isinstance(v, bool): t, v = 'xsd:boolean', str(v).lower()
    elif isinstance(v, (int, float)): t = 'xsd:double'
    return f'    <values>\n        <field>{name}</field>\n        <value xsi:type="{t}">{html.escape(str(v), quote=False)}</value>\n    </values>'
def write(typ, name, label, values):
    body = '\n'.join(val(k, v) for k, v in values)
    x = f'''<?xml version="1.0" encoding="UTF-8"?>
<CustomMetadata xmlns="http://soap.sforce.com/2006/04/metadata" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:xsd="http://www.w3.org/2001/XMLSchema">
    <label>{html.escape(label[:40], quote=False)}</label>
    <protected>false</protected>
{body}
</CustomMetadata>
'''
    open(os.path.join(OUT, f'{typ}.{name}.md-meta.xml'), 'w').write(x)

for s in pack['settings']:
    write('Codey_Recommended_Setting', dev(s['key']), s['key'], [
        ('Active__c', True), ('Area__c', s['area']), ('Fixable__c', bool(s.get('fixable'))), ('Help_Url__c', s['helpUrl']),
        ('Label__c', s['label']), ('Operator__c', s['operator']), ('Reason__c', s['reason']), ('Recommended__c', s['recommended']),
        ('Secret__c', bool(s.get('secret'))), ('Severity__c', s['severity']), ('Source__c', s['source']), ('Target__c', s['target'])])
for u in pack['userTypes']:
    write('Codey_UserType_Permission', dev(u['userType']), u['userType'], [
        ('Active__c', True), ('Note__c', u.get('note', '')), ('Permission_Sets__c', ','.join(u['permissionSets'])), ('User_Type__c', u['userType'])])
for j in pack['adminJobs']:
    write('Codey_Admin_Job', dev(j['key']), j['label'], [
        ('Active__c', True), ('Arg__c', j.get('arg', '')), ('Batch_Size__c', j.get('batchSize')), ('Class_Name__c', j.get('className', '')),
        ('Groups__c', j['groups']), ('Job_Key__c', j['key']), ('Label__c', j['label']), ('Mode__c', j['mode']),
        ('Note__c', j.get('note', '')), ('Order__c', j['order'])])
prov = pack.get('checkProvider', {'mode': 'Builtin', 'addressIp': 'ESM_checkAddressValidation', 'serviceabilityIp': 'ESM_checkServiceQualificationV2', 'serviceName': '', 'batchSize': 200, 'writeBack': True})
write('Codey_Check_Provider', 'Default', 'Default', [
    ('Active__c', True), ('Address_IP__c', prov['addressIp']), ('Apex_Class__c', prov.get('apexClass', '')), ('Batch_Size__c', prov['batchSize']),
    ('Mode__c', prov['mode']), ('Service_Name__c', prov.get('serviceName', '')), ('Serviceability_IP__c', prov['serviceabilityIp']), ('Write_Back__c', prov['writeBack'])])
print('custom metadata records:', len(os.listdir(OUT)))

# readable view of the pack (knowledge/recommended-settings.md)
md = [f"# Recommended settings pack (release {pack['release']})", f"Owner: {pack['owner']} · source of the org's Codey_Recommended_Setting__mdt, Codey_UserType_Permission__mdt and Codey_Admin_Job__mdt records (generated by scripts/build-cmdt.py).", '',
      '## Settings', '| Key | Area | Source | Setting | Rule | Severity | Why |', '|---|---|---|---|---|---|---|']
md += [f"| {x['key']} | {x['area']} | {x['source']} | `{x['target'][:70]}` | {x['operator']} {x['recommended']} | {x['severity']} | {x['reason']} |" for x in pack['settings']]
md += ['', '## Permission sets per user type', '| User type | Permission sets | Note |', '|---|---|---|'] + [f"| {u['userType']} | {', '.join(u['permissionSets'])} | {u.get('note', '')} |" for u in pack['userTypes']]
md += ['', '## Admin jobs (documented order)', '| # | Job | Mode | Class / where | Groups |', '|---|---|---|---|---|'] + [f"| {j['order']} | {j['label']} | {j['mode']} | {j.get('className') or j.get('note', '')} | {j['groups']} |" for j in pack['adminJobs']]
open(os.path.join(ROOT, 'knowledge/recommended-settings.md'), 'w').write('\n'.join(md) + '\n')
print('recommended-settings.md updated')
